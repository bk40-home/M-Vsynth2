"""Generate firmware/gen/vs_bus_tables.h: the bus's laws (EFFECT, EQ, DELAY, CHORUS, the arp) as fixed point (4d).

  python3 tools/gen_bus.py            (run from the repo root; needs Synth2: tools/synth2.py; the output is committed)

As tools/gen_tables.py: whatever Synth2 works out with exp, pow, sin or tan from a knob is worked out here, at
44100 Hz, and written as integers, each table checked read back as the engine reads it. The constants this script
copies from Effects.hpp are looked for there first: if one moved, the script fails rather than write a stale law.
What depends on more than one knob at a time (the EQ's peak) is worked out on the chip (vs_bus.c), from these."""
import cmath, math, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import synth2

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware/gen/vs_bus_tables.h"
FS = 44100.0
out, report = [], []


def fail(msg):
    sys.exit(f"gen_bus: {msg}")


def emit(ctype, name, vals, comment, per=8):
    lim = {"uint16_t": (0, 65535), "int16_t": (-32768, 32767), "uint32_t": (0, 2 ** 32 - 1), "int32_t": (-2 ** 31, 2 ** 31 - 1)}[ctype]
    if min(vals) < lim[0] or max(vals) > lim[1]:
        fail(f"{name}: a value does not fit {ctype}")
    u = "u" if ctype.startswith("u") else ""
    out.append(f"/* {comment} */")
    out.append(f"static const {ctype} {name}[{len(vals)}] = {{")
    out.extend("    " + ", ".join(f"{v}{u}" for v in vals[i:i + per]) + "," for i in range(0, len(vals), per))
    out.extend(["};", ""])


def define(name, value, comment):
    out.append(f"#define {name} {value}{'' if isinstance(value, str) else ''}   /* {comment} */")


def check(name, got, want, bound, relative=True, floor=0.0):
    worst = 0.0
    for g, w in zip(got, want):
        if relative:
            if abs(w) <= floor:
                continue
            e = abs(g - w) / abs(w)
        else:
            e = abs(g - w)
        worst = max(worst, e)
    if worst > bound:
        fail(f"{name}: error {worst:.3g} is past its bound {bound:.3g}")
    report.append(f"  {name:<20} worst {'relative ' if relative else ''}error {worst:.2e} (bound {bound:.0e})")


def need(text, pattern, what):
    if not re.search(pattern, text):
        fail(f"Synth2: {what} moved (Effects.hpp / Synth.hpp)")


def rbj(hz, q, highpass):                               # Effects.hpp Biquad::Set
    w = 2 * math.pi * min(hz, FS * 0.49) / FS
    al, c = math.sin(w) / (2 * q), math.cos(w)
    a0 = 1 + al
    k = (1 + c) / 2 if highpass else (1 - c) / 2
    return [k / a0, (-2 * k if highpass else 2 * k) / a0, k / a0, -2 * c / a0, (1 - al) / a0]


def q29(v):
    return round(v * 2 ** 29)


def main():
    s2 = synth2.root()
    fx = (s2 / "EngineCore/Effects.hpp").read_text()
    mt = (s2 / "EngineCore/MeasuredTables.hpp").read_text()
    syn = (s2 / "EngineCore/Synth.hpp").read_text()
    par = (s2 / "EngineCore/Params.hpp").read_text()
    T = lambda n, size: (lambda a: a if len(a) == size else fail(f"Synth2: {n} has {len(a)} entries, not {size}"))(synth2.c_array(mt, n))

    out.extend(["/* SPDX-License-Identifier: GPL-3.0-only */",
                "/* GENERATED by tools/gen_bus.py from Synth2's EngineCore (Effects.hpp, MeasuredTables.hpp, Synth.hpp,",
                " * Params.hpp: MIT, Copyright (c) 2026 Francois Chabloz). Do not edit by hand.",
                " * The bus's laws at 44100 Hz as fixed point; each checked against Synth2's double as it was written. */",
                "#pragma once", "#include <stdint.h>", ""])

    # ---- EFFECT's filters: the RBJ low-pass at 400 Hz x 40^(ctl2 / 127), Q 3; the two high-passes
    need(fx, r"lp2_\.Set\(400\.0 \* std::pow\(40\.0, p\[kEffectCtrl2\] / 127\.0\), 3\.0, false, sr_\)", "EFFECT's low-pass")
    need(fx, r"hp2_\.Set\(96\.2836231, 2\.37189425, true, sr_\)", "a.d.1's high-pass")
    need(fx, r"hp2_\.Set\(100\.0, 2\.29, true, sr_\)", "the distortions' high-pass")
    lp = []
    for c in range(128):
        lp += [q29(v) for v in rbj(400.0 * 40.0 ** (c / 127.0), 3.0, False)]
    emit("int32_t", "VS_FX_LP_Q29", lp, "EFFECT: the RBJ low-pass at 400 Hz x 40^(CTRL2 / 127), Q 3: b0 b1 b2 a1 a2 by CTRL2, Q29", 5)
    emit("int32_t", "VS_FX_HP_AD1_Q29", [q29(v) for v in rbj(96.2836231, 2.37189425, True)], "a.d.1's RBJ high-pass, 96.3 Hz Q 2.37: b0 b1 b2 a1 a2, Q29", 5)
    emit("int32_t", "VS_FX_HP_DIST_Q29", [q29(v) for v in rbj(100.0, 2.29, True)], "a.d.2's and d.d.'s RBJ high-pass, 100 Hz Q 2.29, Q29", 5)

    # ---- a.d.1 (the fitted model): drive / out by CTRL1, the loop's constants, the two curves on u = w / (|w| + 1)
    need(fx, r"kBias1 = 0\.724662338, kLoopGain = 7\.76408919, kGain2 = 1\.46001006, kBias2 = 0\.233492458", "a.d.1's constants")
    need(fx, r"kAd1Curve1\(0\.81459387, 1\.58674746, 0\.581142865, 1\.89364943\)", "a.d.1's first curve")
    need(fx, r"kAd1Curve2\(1\.26459138, 2\.39715448, 0\.856279228, 1\.48562438\)", "a.d.1's second curve")
    need(fx, r"95\.3658895 / sr_\), z0 = f1\(kBias1\), s0 = f2\(kBias2\)", "a.d.1's loop low-pass")
    need(fx, r"std::tan\(M_PI \* 263\.480241 / sr_\), k2 = std::tan\(M_PI \* 30\.2652942 / sr_\)", "a.d.1's high-passes")
    drive, aout = T("kAd1Drive", 128), T("kAd1Out", 128)
    emit("int32_t", "VS_AD1_DRIVE_Q12", [round(v * 4096) for v in drive], "a.d.1: the drive by CTRL1 (70 dB over the knob), Q12")
    emit("int32_t", "VS_AD1_OUT_Q24", [round(v * 2 ** 24) for v in aout], "a.d.1: the output gain by CTRL1 (x (LEVEL + 2) / 129), Q24")

    def curve(L, K, nl, nk, w):
        lim, knee = (L, K) if w >= 0 else (nl, nk)
        return w / (1.0 + abs(w / lim) ** knee) ** (1.0 / knee)
    NC = 1024
    z0 = curve(0.81459387, 1.58674746, 0.581142865, 1.89364943, 0.724662338)
    s0 = curve(1.26459138, 2.39715448, 0.856279228, 1.48562438, 0.233492458)
    for nm, prm, off in (("1", (0.81459387, 1.58674746, 0.581142865, 1.89364943), z0), ("2", (1.26459138, 2.39715448, 0.856279228, 1.48562438), s0)):
        tab = []
        for i in range(NC + 1):
            u = 2.0 * i / NC - 1.0
            if i == 0:
                tab.append(-prm[2])
            elif i == NC:
                tab.append(prm[0])
            else:
                tab.append(curve(*prm, u / (1.0 - abs(u))))
        emit("int32_t", f"VS_AD1_CURVE{nm}_Q24", [round((v - off) * 2 ** 24) for v in tab],
             f"a.d.1's curve {nm}, w / (1 + |w / L|^k)^(1 / k) (L, k a side), less its value at its bias (Synth2 takes it off after), on u = w / (|w| + 1) at {NC} steps over -1..1, Q24 (linear between)", 6)
        ws = [x / 64.0 for x in range(-2000, 2001)]
        got = []
        for w in ws:
            x = (w / (abs(w) + 1.0) + 1.0) * NC / 2
            i = min(int(x), NC - 1)
            got.append((tab[i] + (tab[i + 1] - tab[i]) * (x - i)))   # (checked before the offset)
        check(f"VS_AD1_CURVE{nm}", got, [curve(*prm, w) for w in ws], 2e-4, relative=False)
    a = 1.0 - math.exp(-2 * math.pi * 95.3658895 / FS)
    k1, k2 = math.tan(math.pi * 263.480241 / FS), math.tan(math.pi * 30.2652942 / FS)
    for nm, v, q, c in (("VS_AD1_BIAS1_Q24", 0.724662338, 24, "the first curve's bias"), ("VS_AD1_LOOP_Q24", 7.76408919, 24, "the loop's gain"),
                        ("VS_AD1_GAIN2_Q24", 1.46001006, 24, "the second curve's input gain"), ("VS_AD1_BIAS2_Q24", 0.233492458, 24, "its bias"),
                        ("VS_AD1_LPA_Q31", a, 31, "the loop's one-pole low-pass at 95.4 Hz, a"),
                        ("VS_AD1_H1C_Q30", 1 / (1 + k1), 30, "the bilinear high-pass at 263.5 Hz: (x - x1) / (1 + k)"),
                        ("VS_AD1_H1D_Q30", (1 - k1) / (1 + k1), 30, ".. + (1 - k) / (1 + k) y1"),
                        ("VS_AD1_H2C_Q30", 1 / (1 + k2), 30, "the one at 30.3 Hz"), ("VS_AD1_H2D_Q30", (1 - k2) / (1 + k2), 30, "..")):
        define(nm, round(v * 2 ** q), c)
    out.append("")

    # ---- a.d.2 and d.d.
    need(fx, r"const double a = std::fabs\(u\) / 0\.05;", "a.d.2's curve grid")
    d2, c2 = T("kAd2Drive", 33), T("kAd2Curve", 201)

    def drive2(c1):
        x = min(max(c1, 0), 127) / 4.0
        i = min(int(x), 31)
        t = min(1.0, (min(max(c1, 0), 127) - 4.0 * i) / (3.0 if i == 31 else 4.0))
        return math.exp(math.log(d2[i]) * (1 - t) + math.log(d2[i + 1]) * t)
    emit("int32_t", "VS_AD2_DRIVE_Q16", [round(drive2(c) * 65536) for c in range(128)], "a.d.2: the drive by CTRL1 (log between Synth2's 33 points), Q16")
    emit("int32_t", "VS_AD2_CURVE_Q24", [round(v * 2 ** 24) for v in c2], "a.d.2: its odd curve at |u| = 0, 0.05 .. 10 (held above), Q24")
    slope, peak = T("kDdSlope", 128), T("kDdPeak", 128)
    emit("int32_t", "VS_DD_RATE_Q16", [round(s / p * 65536) for s, p in zip(slope, peak)], "d.d.: the fold's rate slope / peak by CTRL1, Q16")
    emit("int32_t", "VS_DD_PEAK_Q24", [round(p * 2 ** 24) for p in peak], "d.d.: its peak by CTRL1, Q24")

    # ---- deci., r.m., comp., the phasers
    need(fx, r"0\.00643 \* std::exp2\(p\[kEffectCtrl2\] / 8 - 8\)", "deci.'s quantiser")
    need(fx, r"std::tan\(M_PI \* 14016\.0 / sr_\)", "deci.'s low-pass")
    emit("int32_t", "VS_DECI_Q_Q24", [round(0.00643 * 2.0 ** (k - 8) * 2 ** 24) for k in range(16)], "deci.: the quantiser's step by CTRL2 / 8, Q24")
    k = math.tan(math.pi * 14016.0 / FS)
    define("VS_DECI_B_Q30", round(k / (1 + k) * 2 ** 30), "deci.'s one-pole low-pass at 14 kHz: b (x + x1) ..")
    define("VS_DECI_A_Q30", round((1 - k) / (1 + k) * 2 ** 30), ".. + a y1")
    need(fx, r"std::pow\(8000\.0, p\[kEffectCtrl1\] / 127\.0\) / sr_", "r.m.'s frequency")
    emit("uint32_t", "VS_RM_INC_Q32", [round(8000.0 ** (c / 127.0) / FS * 2 ** 32) for c in range(128)], "r.m.: the sine's phase step a frame by CTRL1 (1 Hz .. 8 kHz), Q32")
    m = re.search(r"c\[11\] = \{([^}]*)\};\s*static constexpr double t\[11\] = \{([^}]*)\}", fx)
    if not m:
        fail("Synth2: comp.'s time table moved")
    cc = [float(x) for x in m.group(1).split(",")]
    tt = [float(x) for x in m.group(2).split(",")]

    def comp_tau(v):
        i = 0
        while i < 9 and v > cc[i + 1]:
            i += 1
        f = min(max((v - cc[i]) / (cc[i + 1] - cc[i]), 0.0), 1.0)
        return math.exp(math.log(tt[i]) * (1 - f) + math.log(tt[i + 1]) * f)
    emit("uint32_t", "VS_COMP_A_Q31", [round((1.0 - math.exp(-1.0 / (comp_tau(c) * FS))) * 2 ** 31) for c in range(128)],
         "comp.: the detector's coefficient a frame by CTRL2 (0.1 ms .. 0.2 s), Q31")
    need(fx, r"std::pow\(10\.0, -\(10\.0 \+ 0\.3125 \* p\[kEffectCtrl1\]\) / 5\.0\)", "comp.'s Gmax")
    need(fx, r"std::pow\(env_\[ch\] / 0\.2604, 4\.0\)", "comp.'s knee")
    emit("int32_t", "VS_COMP_LGMAX_Q24", [round(-(10.0 + 0.3125 * c) / 5.0 * math.log2(10.0) * 2 ** 24) for c in range(128)],
         "comp.: log2(Gmax^-4) by CTRL1, Gmax = 10 + 0.3125 CTRL1 dB, Q24")
    emit("int32_t", "VS_COMP_OUT_Q24", [round(10.0 ** (1.5 * (c / 127.0 - 1.0)) * 2 ** 24) for c in range(128)], "comp.: the output gain by LEVEL (-30 dB .. 0), Q24")
    define("VS_COMP_LKNEE_Q24", round(math.log2(1 / 0.2604) * 2 ** 24), "log2(1 / 0.2604): the knee")
    sp = [round(math.log2(1.0 + 2.0 ** (-i / 64.0)) * 2 ** 24) for i in range(64 * 32 + 1)]
    emit("int32_t", "VS_SOFTPLUS_Q24", sp, "log2(1 + 2^-d), d = 0..32 in steps of 1/64, Q24: log2(a + b) from log2 a and log2 b", 6)
    need(fx, r"254\.6 \* std::exp2\(pos_\) / sr_, a = \(t - 1\) / \(t \+ 1\)", "the phasers' stage frequency")
    need(fx, r"0\.02625 \* p\[kEffectCtrl1\]", "the phasers' swing")
    need(fx, r"4\.0 \* h \* 0\.6418 \* std::exp2\(\(p\[kEffectCtrl2\] - 64\) / 12\.9\) / sr_", "the phasers' rate")
    ap = []
    for i in range(-2 * 256, 6 * 256 + 1):
        t = math.pi * 254.6 * 2.0 ** (i / 256.0) / FS
        ap.append(round((t - 1) / (t + 1) * 2 ** 30))
    emit("int32_t", "VS_PH_A_Q30", ap, "the phasers: the allpass coefficient (t - 1) / (t + 1), t = pi 254.6 Hz 2^pos / fs, pos = -2..6 octaves (index pos + 2) in steps of 1/256, Q30", 6)
    emit("uint32_t", "VS_PH_RATE_Q32", [round(4.0 * 0.6418 * 2.0 ** ((c - 64) / 12.9) / FS * 2 ** 32) for c in range(128)],
         "the phasers: 4 f / fs by CTRL2 (octaves a frame per octave of swing), Q32: x H for the step")

    # ---- EQ: the peak's knobs (the coefficients are worked out on the chip), the tone's
    need(fx, r"50\.0 \* std::pow\(320\.0, p\[kEqFreq\] / 127\.0\)", "the EQ's frequency")
    need(fx, r"3\.18 \* std::exp2\(\(p\[kEqQ\] - 64\) / 38\.16\)", "the EQ's Q")
    need(fx, r"std::pow\(10\.0, \(p\[kEqLevel\] - 64\) \* 50\.0 / 127\.0 / 20\.0\)", "the EQ's gain")
    emit("int32_t", "VS_EQ_W0_Q29", [round(2 * math.pi * min(50.0 * 320.0 ** (f / 127.0), FS * 0.49) / FS * 2 ** 29) for f in range(128)],
         "the EQ's peak: w0 = 2 pi f0 / fs by FREQ (f0 = 50 Hz x 320^(FREQ / 127)), Q29")
    emit("int32_t", "VS_EQ_LG_Q24", [round((l - 64) * 50.0 / 127.0 / 20.0 * math.log2(10.0) * 2 ** 24) for l in range(128)],
         "its gain G by LEVEL: log2 G, (LEVEL - 64) x 50 / 127 dB, Q24")
    emit("int32_t", "VS_EQ_LQ_Q24", [round(math.log2(3.18 * 2.0 ** ((q - 64) / 38.16)) * 2 ** 24) for q in range(128)],
         "its poles' Q by Q (for a boost; a cut's is Q x G): log2 Q, Q = 3.18 x 2^((Q - 64) / 38.16), Q24")
    tone = T("kDelayToneHz", 128)
    kk = [math.pi * hz / FS for hz in tone]
    emit("uint32_t", "VS_DTONE_G_Q30", [round((1.0 if t > 64 else k) / (1.0 + k) * 2 ** 30) for t, k in enumerate(kk)],
         "DELAY's TONE, as EQ TONE (a bilinear one-pole, no prewarp; 64: none): g, Q30")
    emit("int32_t", "VS_DTONE_B_Q30", [round((1.0 - k) / (1.0 + k) * 2 ** 30) for k in kk], "its b, Q30")

    # ---- DELAY
    m = re.search(r"kDelayBeats\[20\] = \{([^}]*)\}", fx)
    beats = [eval(x.strip()) for x in m.group(1).split(",") if x.strip()] if m else []
    if len(beats) != 20:
        fail("Synth2: kDelayBeats moved")
    emit("uint32_t", "VS_DLY_BEAT", [round(b * 60.0 * FS * 256.0) for b in beats], "DELAY TIME: beats x 60 x fs x 256 (/ the tempo in bpm Q8: frames; then down to a multiple of 4)")
    need(fx, r"0\.1 \* sr_ \* std::pow\(10\.0, \(sd - 63\) / 21\.0\)", "DELAY's spread")
    emit("uint16_t", "VS_DLY_SPREAD", [0] + [math.floor(0.1 * FS * 10.0 ** ((sd - 63) / 21.0)) for sd in range(1, 64)], "DELAY SPREAD: one side later by this many frames, |SPREAD - 64| = 0..63", 16)
    need(fx, r"kGlideSeconds = 0\.215", "DELAY's glide")
    need(fx, r"kClearFadeSeconds = 0\.015", "DELAY's clear fade")
    define("VS_DLY_GLIDE_Q31", round((1.0 - math.exp(-1.0 / (0.215 * FS))) * 2 ** 31) , "a new time glides there, tau 0.215 s: the coefficient a frame")
    define("VS_DLY_FADE", f"{max(1, int(FS * 0.015))}u", "a clear fades the echoes out over 15 ms")
    define("VS_DLY_MIN", f"{math.floor(1e-4 * FS)}u", "the shortest time, frames (0.1 ms)")

    # ---- CHORUS
    m = re.search(r"static constexpr short t\[128\] = \{([^}]*)\}", fx)
    ct = [int(x) for x in m.group(1).split(",") if x.strip()] if m else []
    if len(ct) != 128:
        fail("Synth2: the chorus's time table moved")
    emit("uint16_t", "VS_CHO_TIME", ct, "CHORUS TIME: the base delay in frames (44.1 kHz)", 16)
    need(fx, r"v <= 0 \? 0\.01 : 2\.9409 \* std::exp2\(\(v - 64\) / 8\.89\)", "the chorus's rate")
    need(fx, r"\(std::pow\(100\.0, v / 127\.0\) - 1\.0\) / 99\.0", "the chorus's depth")
    need(fx, r"f\[4\] = \{10, 36, 124, 400\}, a\[4\] = \{1\.0, 0\.98, 0\.92, 0\.62\}", "the chorus's swing")

    def rate(v):
        return 0.01 if v <= 0 else 2.9409 * 2.0 ** ((v - 64) / 8.89)

    def swing(hz):
        f, a = (10, 36, 124, 400), (1.0, 0.98, 0.92, 0.62)
        if hz <= f[0]:
            return 1.0
        i = 0
        while i < 2 and hz > f[i + 1]:
            i += 1
        t = min(max(math.log(hz / f[i]) / math.log(f[i + 1] / f[i]), 0.0), 1.0)
        return a[i] + (a[i + 1] - a[i]) * t
    emit("uint32_t", "VS_CHO_INC_Q32", [round(rate(v) / FS * 2 ** 32) for v in range(128)], "CHORUS RATE: its sine's phase step a frame (0.01 Hz at 0), Q32")
    emit("int32_t", "VS_CHO_DEPTH_Q16", [round((100.0 ** (v / 127.0) - 1.0) / 99.0 * 65536) for v in range(128)], "CHORUS DEPTH: the swing D (x the base), Q16")
    emit("int32_t", "VS_CHO_SWING_Q16", [round(swing(rate(v)) * 65536) for v in range(128)], "the swing's shrink at audio rates, by RATE, Q16")

    # ---- the arp
    m = re.search(r"kArpBeats\[19\] = \{([^}]*)\}", par)
    ab = [eval(x.strip()) for x in m.group(1).split(",") if x.strip()] if m else []
    if len(ab) != 19:
        fail("Synth2: kArpBeats moved")
    emit("uint32_t", "VS_ARP_STEP", [round(b * 60.0 * FS * 256.0) for b in ab], "ARP BEAT: beats x 60 x fs x 256 (/ the tempo in bpm Q8: frames, Q8 more for the step's fraction)")

    OUT.write_text("\n".join(out) + "\n")
    print(f"gen_bus: {OUT.relative_to(ROOT)}: {sum(1 for l in out if l.startswith('static const'))} tables")
    print("\n".join(report))


main()
