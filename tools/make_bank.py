"""Build the factory bank: a folder of .sy1 files -> firmware/gen/vs_factory.h (128 records of vs_patch.h).

  python3 tools/make_bank.py [FOLDER]        (default tools/bank/factory; run from the repo root; rebuild after)

Slots as Synth2's patch library has them (PatchLibrary.hpp): a file whose name starts with a number 1..128 takes
that slot ("012.sy1", "012_Lead.sy1"); the other files fill the free slots in name order; what is left is EMPTY.
Each file is loaded as tools/sy1.py loads it (old versions converted, values clamped, the name made ASCII).
Fails on two files for one slot, more than 128 files, or a file that does not load."""
import re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sy1

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware/gen/vs_factory.h"
NSLOT = 128


def main():
    folder = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tools/bank/factory"
    files = sorted(folder.glob("*.sy1"), key=lambda f: f.name.lower())
    if not files or len(files) > NSLOT:
        sys.exit(f"make_bank: {len(files)} .sy1 files in {folder} (1..{NSLOT})")
    slots, loose = [None] * NSLOT, []
    for f in files:
        m = re.match(r"(\d+)", f.name)
        n = int(m.group(1)) if m else 0
        if 1 <= n <= NSLOT:
            if slots[n - 1]:
                sys.exit(f"make_bank: slot {n} twice: {slots[n - 1].name}, {f.name}")
            slots[n - 1] = f
        else:
            loose.append(f)
    for f in loose:
        slots[slots.index(None)] = f
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           f"/* GENERATED by tools/make_bank.py from {folder.relative_to(ROOT) if folder.is_relative_to(ROOT) else folder.name}/. Do not edit by hand.",
           " * The factory bank: 128 records of vs_patch.h (vs_rec_t), EMPTY where the folder has no patch.",
           " * The patches: Synth2's \"Synth2 Factory\" bank (MIT, Copyright (c) 2026 Francois Chabloz): LICENSING.md. */",
           "#pragma once", "#include <stdint.h>", "",
           f"#define VS_FACTORY_N {sum(1 for s in slots if s)}u                        /* patches in it */",
           "static const uint8_t VS_FACTORY[128][120] = {"]
    for n, f in enumerate(slots):
        if f:
            p = sy1.parse(f.read_bytes())
            r, what = sy1.pack(p), f"{n + 1:03d} {p['name'].rstrip()}"
        else:
            r, what = sy1.empty(), f"{n + 1:03d} (empty)"
        out.append(f"    {{   /* {what} */")
        out += ["        " + ", ".join(str(b) for b in r[i:i + 24]) + "," for i in range(0, len(r), 24)]
        out.append("    },")
    out += ["};", ""]
    OUT.write_text("\n".join(out))
    print(f"make_bank: {OUT.relative_to(ROOT)}: {sum(1 for s in slots if s)} patches of {NSLOT} slots")


main()
