"""Generate firmware/gen/vs_wave.h: M-Vsynth2's oscillator tables, and firmware/gen/vs_gate_tab.h (Stage 3's gate).

  python3 tools/gen_wave.py            (run from the repo root; the output is committed)

Synth2 keeps one table a MIDI note (11 MB). The FM-1 has 568 KB of flash, so here (proposal 4.2, decision 4a):
  table 0        notes 0..23
  table 1 + k    notes 24 + 6k .. 29 + 6k, k = 0..17 (up to note 131: OSC2 at +60 reaches past 127)
each 2048 points + 1 (the first again, so an interpolated read needs no wrap), int16, 1.0 = 16384 (Q14: the series'
overshoot, 1.18, fits). A table holds every harmonic h with h x f(top note of its range) < 44100 - ALIAS_FLOOR: what
aliases at the range's top note lands above ALIAS_FLOOR (18 kHz), and its lowest note is still full to ~17.7 kHz.
  saw       falling, +1 at phase 0: sum 2 / (pi h) sin(2 pi h p)
  triangle  peak +1 at phase 0.25: odd h, +-8 / (pi h)^2
            Its harmonics fall as 1 / h^2, so it has one table per 24 notes (6 in all). At the lowest note of a
            range the table stops at a quarter of the band (note 48: 6.8 kHz); what it leaves out is 56 dB and
            more under the fundamental (tools/compare: detune-tri-*). (The engine reads the tables from RAM, the
            flash's cache being 32 KB: proposal 3.5. Fewer triangle tables is what makes them fit.)
  sine      one cycle
The script fails if a table would clip or its spectrum is not what was asked for."""
import math, sys
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
FS = 44100.0
N = 2048
ONE = 16384
ALIAS_FLOOR = 18000.0
NT = 19
NT_TRI = 6                                               # triangle tables: one per two octaves (see the docstring)


def top_note(t):
    return 23 if t == 0 else 24 + 6 * (t - 1) + 5


def tri_top_note(t):
    return 24 * t + 23


def harmonics(t, top=top_note):
    f = 440.0 * 2.0 ** ((top(t) - 69) / 12.0)
    return max(1, min(N // 2 - 1, int((FS - ALIAS_FLOOR) / f)))


def series(h_max, amp):
    spec = np.zeros(N, dtype=complex)
    for h in range(1, h_max + 1):
        a = amp(h)
        spec[h] = -0.5j * a
        spec[N - h] = 0.5j * a
    return np.fft.ifft(spec).real * N


def saw_amp(h):
    return 2.0 / (math.pi * h)


def tri_amp(h):
    if not h & 1:
        return 0.0
    return (-8.0 if (h >> 1) & 1 else 8.0) / (math.pi * math.pi * h * h)


def q(x):
    v = np.rint(x * ONE).astype(int)
    if abs(v).max() > 32767:
        sys.exit("gen_wave: a table clips")
    return v


def c_rows(v):
    v = list(v) + [v[0]]                                 # point N = point 0
    return "\n".join("    " + ", ".join(str(int(x)) for x in v[i:i + 16]) + "," for i in range(0, len(v), 16))


def main():
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* GENERATED by tools/gen_wave.py. Do not edit by hand. Band-limited oscillator tables after Synth2's",
           " * WaveTableSet (MIT, Copyright (c) 2026 Francois Chabloz): %d saw and %d triangle tables, %d + 1 points, Q14. */" % (NT, NT_TRI, N),
           "#pragma once", "#include <stdint.h>", "",
           "#define VS_WAVE_BITS 11u                        /* log2 of a table's length */",
           "#define VS_WAVE_N %du" % N,
           "#define VS_WAVE_NT %du                          /* tables a shape */" % NT,
           "#define VS_WAVE_ONE %d                       /* 1.0 */" % ONE, "",
           "/* the table of a note (0..131; above: the last) */",
           "static inline uint32_t vs_wave_of(uint32_t note)",
           "{", "    uint32_t t = note < 24u ? 0u : 1u + (note - 24u) / 6u;",
           "    return t < VS_WAVE_NT ? t : VS_WAVE_NT - 1u;", "}",
           "#define VS_TRI_NT %du                            /* triangle tables: one per 24 notes */" % NT_TRI,
           "static inline uint32_t vs_tri_of(uint32_t note)",
           "{", "    uint32_t t = note / 24u;", "    return t < VS_TRI_NT ? t : VS_TRI_NT - 1u;", "}", ""]
    for name, amp, nt, top, dim in (("VS_SAW", saw_amp, NT, top_note, "VS_WAVE_NT"), ("VS_TRI", tri_amp, NT_TRI, tri_top_note, "VS_TRI_NT")):
        out.append("static const int16_t %s[%s][VS_WAVE_N + 1u] = {" % (name, dim))
        for t in range(nt):
            h = harmonics(t, top)
            x = series(h, amp)
            spec = np.abs(np.fft.rfft(x)) / (N / 2)
            for k in range(1, N // 2):                   # the check: the harmonics asked for, nothing else
                want = abs(amp(k)) if k <= h else 0.0
                if abs(spec[k] - want) > 1e-9:
                    sys.exit("gen_wave: %s table %d harmonic %d" % (name, t, k))
            out.append("    {   /* %d: to note %d, %d harmonics */" % (t, top(t), h))
            out.append(c_rows(q(x)))
            out.append("    },")
        out.append("};")
        out.append("")
    out.append("static const int16_t VS_SINE[VS_WAVE_N + 1u] = {")
    out.append(c_rows(q(np.sin(2 * np.pi * np.arange(N) / N))))
    out.append("};")
    out.append("")
    (ROOT / "firmware/gen/vs_wave.h").write_text("\n".join(out))

    # ---- the gate's own small tables (Stage 3 only: tools/gen_tables.py replaces them at Stage 2 proper)
    g = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/gen_wave.py for the Stage 3 gate (firmware/src/vs_gate.c). Do not edit by hand.",
         " * Laws: Synth2's Filter.hpp (MIT, Copyright (c) 2026 Francois Chabloz). */",
         "#pragma once", "#include <stdint.h>", "",
         "/* SVF f = 2 sin(pi fc / (2 fs)), fc = 16.7 Hz x 2^(knob / 12.624), knob held at 125: Q14, per knob */",
         "static const int16_t VS_GATE_SVF_F[128] = {"]
    f = [2.0 * math.sin(math.pi * min(16.7 * 2.0 ** (min(k, 125) / 12.624), FS) / (2.0 * FS)) for k in range(128)]
    g.append("\n".join("    " + ", ".join(str(round(v * 16384)) for v in f[i:i + 16]) + "," for i in range(0, 128, 16)))
    g += ["};", "",
          "/* the filters' output limiter: gain (1 + (e / 1.038)^11.54)^(-0.856 / 11.54), Q15, e = 0..4 in steps of 1/32 */",
          "#define VS_GATE_LIM_N 129u",
          "static const uint16_t VS_GATE_LIM[VS_GATE_LIM_N] = {"]
    lim = [min(32767, round(32768 * (1.0 + (i / 32.0 / 1.038) ** 11.54) ** (-0.856 / 11.54))) for i in range(129)]
    g.append("\n".join("    " + ", ".join(str(v) for v in lim[i:i + 16]) + "," for i in range(0, 129, 16)))
    g += ["};", ""]
    (ROOT / "firmware/gen/vs_gate_tab.h").write_text("\n".join(g))
    flash = (NT + NT_TRI + 1) * (N + 1) * 2
    print("gen_wave: firmware/gen/vs_wave.h (%d B of flash), vs_gate_tab.h; harmonics %s" %
          (flash, [harmonics(t) for t in range(NT)]))


main()
