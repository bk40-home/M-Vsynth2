"""Generate firmware/gen/vs_tables.h: the voice's laws as fixed-point tables (Stage 2).

  python3 tools/gen_tables.py            (run from the repo root; needs Synth2: tools/synth2.py; the output is committed)

The chip has no FPU: whatever Synth2 works out with exp, pow, sin or tan is worked out here and written as integers.
Nothing is re-measured: each table is a Synth2 table or formula at the FM-1's sample rate (44100), in the format the
engine reads. The bus (EFFECT, EQ, DELAY, CHORUS) and the LPDL filter get their tables with their code (Stages 4c, 4d).

Each table is checked as it is written: read back the way the engine will read it (with its interpolation where it
has one) and compared with Synth2's own double. The script fails if one is outside its bound, so a format that is
too coarse never reaches the firmware. The bounds are printed."""
import math, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import synth2

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware/gen/vs_tables.h"
FS = 44100.0
CTL = 16
out, report = [], []


def fail(msg):
    sys.exit(f"gen_tables: {msg}")


def const(text, name):
    m = re.search(r"\b" + name + r"\s*=\s*([^;]+);", synth2.strip_comments(text))
    if not m or not re.fullmatch(r"[-+0-9.eE/* ()xXa-fA-F]+", m.group(1).strip()):
        fail(f"Synth2: constant {name} not found")
    return float(eval(m.group(1)))


def emit(ctype, name, vals, comment, per=8, fmt="%d"):
    lim = {"uint16_t": (0, 65535), "int16_t": (-32768, 32767), "uint32_t": (0, 2 ** 32 - 1), "int32_t": (-2 ** 31, 2 ** 31 - 1)}[ctype]
    if min(vals) < lim[0] or max(vals) > lim[1]:
        fail(f"{name}: a value does not fit {ctype}")
    u = "u" if ctype.startswith("u") else ""
    out.append(f"/* {comment} */")
    out.append(f"static const {ctype} {name}[{len(vals)}] = {{")
    out.extend("    " + ", ".join((fmt % v) + u for v in vals[i:i + per]) + "," for i in range(0, len(vals), per))
    out.extend(["};", ""])


def check(name, got, want, bound, relative=True, floor=0.0):
    """got / want: lists of floats; the worst error must be within bound (relative to want, where want > floor)."""
    worst = 0.0
    for g, w in zip(got, want):
        if relative:
            if abs(w) <= floor:
                continue
            e = abs(g - w) / abs(w)
        else:
            e = abs(g - w)
        worst = max(worst, e)
    if worst > bound:
        fail(f"{name}: error {worst:.3g} is past its bound {bound:.3g}")
    report.append(f"  {name:<18} worst {'relative ' if relative else ''}error {worst:.2e} (bound {bound:.0e})")


def lerp_table(tab, x, scale):
    """The engine's read: tab at x (in table steps), linear between two entries."""
    i = min(int(x), len(tab) - 2)
    return (tab[i] + (tab[i + 1] - tab[i]) * (x - i)) / scale


def main():
    s2 = synth2.root()
    note = synth2.pin_note(s2)
    if note:
        print(note)
    mt = (s2 / "EngineCore/MeasuredTables.hpp").read_text()
    voice = (s2 / "EngineCore/Voice.hpp").read_text()
    filt = (s2 / "EngineCore/Filter.hpp").read_text()
    T = lambda n, size: (lambda a: a if len(a) == size else fail(f"Synth2: {n} has {len(a)} entries, not {size}"))(synth2.c_array(mt, n))

    out.extend(["/* SPDX-License-Identifier: GPL-3.0-only */",
                "/* GENERATED by tools/gen_tables.py from Synth2's EngineCore (MeasuredTables.hpp, Voice.hpp, Filter.hpp,",
                " * Envelope.hpp, Lfo.hpp: MIT, Copyright (c) 2026 Francois Chabloz). Do not edit by hand.",
                " * The voice's laws at 44100 Hz as fixed-point tables; each was checked against Synth2's double as it was",
                " * written (the bounds: tools/gen_tables.py prints them). */",
                "#pragma once", "#include <stdint.h>", ""])

    # ---- constants of Voice.hpp / Filter.hpp
    noise_level, noise_fm = const(voice, "kNoiseLevel"), const(voice, "kNoiseFm")
    sync_reset, fm_ref = const(voice, "kSyncResetPhase"), const(voice, "kFmRefInc")
    osc_amp, phase_units = const(voice, "kOscAmplitude"), const(voice, "kPhaseUnits")
    agc_t, agc_k, lim_floor = const(filt, "kLadderAgcThreshold"), const(filt, "kAgcExponent"), const(filt, "kLimitFloor")
    def tc(member):                                      # a follower's time constant in Prepare -> its coefficient
        m = re.search(member + r"\s*=\s*1\.0\s*-\s*std::exp\(-1\.0\s*/\s*\(([0-9.]+)\s*\*\s*sampleRate\)\)", filt)
        if not m:
            fail(f"Synth2: {member}'s time constant not found in Filter.hpp")
        return round((1.0 - math.exp(-1.0 / (float(m.group(1)) * FS))) * 2 ** 31)

    seed = re.search(r"kNoiseSeed\s*=\s*(0x[0-9A-Fa-f]+)", voice)
    if phase_units != 2.0 ** 27 or not seed:
        fail("Synth2: OSC1's phase grid is no longer 2^-27 cycle, or the noise seed moved")
    out.extend([
        "#define VS_T_FS 44100u                          /* the rate these tables are for */",
        "#define VS_T_CTL 16u                            /* the control block the per-block ones are for */",
        f"#define VS_NOISE_Q14 {round(noise_level * 16384)}                      /* the noise's level, +-{noise_level} (Q14, as the wave tables) */",
        f"#define VS_NOISE_FM_Q14 {round(noise_fm * 16384)}                   /* and as an FM source, +-{noise_fm} */",
        f"#define VS_NOISE_SEED {int(seed.group(1), 16)}u                    /* the 20 bits a voice slot's noise starts from (and a sync restarts at) */",
        f"#define VS_SYNC_RESET_Q32 {round(sync_reset * 2 ** 32)}u               /* OSC2's phase after a forward-wrap sync, {sync_reset:g} cycle */",
        "#define VS_OSC1_PHASE_MASK 0xFFFFFFE0u          /* OSC1's step in whole 2^-27 cycles: its low 5 bits clear */",
        f"#define VS_OSC_AMP_Q15 {round(osc_amp * 32768)}                     /* an oscillator's level at GAIN 64, velocity 127: {osc_amp} */",
        f"#define VS_LIMIT_FLOOR_Q14 {round(lim_floor * 16384)}                 /* the output limiter does nothing below {lim_floor} */",
        f"#define VS_AGC_T_Q14 {round(agc_t * 16384)}                      /* the LP24 AGC's threshold, {agc_t} */",
        "/* the followers' coefficients a frame, 1 - e^(-1 / (seconds x fs)), Q31 (Filter.hpp VoiceFilter::Prepare) */",
        f"#define VS_LIMIT_ATK_Q31 {tc('limitAttack_')}u               /* the output limiter: up */",
        f"#define VS_LIMIT_REL_Q31 {tc('limitRelease_')}u                /* down */",
        f"#define VS_AGC_ATK_Q31 {tc('agcAttack_')}u                 /* LP24's AGC: up */",
        f"#define VS_AGC_REL_Q31 {tc('agcRelease_')}u                   /* down */", ""])

    # ---- pitch
    exp2 = [round(2.0 ** (i / 256.0) * 2 ** 30) for i in range(257)]
    emit("uint32_t", "VS_EXP2_Q30", exp2, "2^(i / 256), i = 0..256, Q30: a pitch ratio for any fraction of an octave, linear between entries")
    xs = [k / 4096.0 for k in range(4097)]
    check("VS_EXP2_Q30", [lerp_table(exp2, x * 256, 2 ** 30) for x in xs], [2.0 ** x for x in xs], 2e-6)
    inc = [round(440.0 * 2.0 ** ((n - 69) / 12.0) / FS * 2 ** 32) for n in range(120, 132)]
    emit("uint32_t", "VS_NOTE_INC_Q32", inc, "the phase step of MIDI notes 120..131, f x 2^32 / 44100; an octave down: >> 1", 6)

    # ---- envelopes (Envelope.hpp Adsr::Configure)
    atk = T("kAmpAttackSeconds", 128)
    tau = T("kEnvTauSeconds", 128)
    a_step = [round(2 ** 30 / max(1.0, t * FS)) for t in atk]
    emit("uint32_t", "VS_ATK_STEP_Q30", a_step, "attack: the level's step a frame, 1 / (seconds x fs), Q30 (linear to 1.0 = 2^30)")
    check("VS_ATK_STEP_Q30", [v / 2 ** 30 for v in a_step], [1.0 / max(1.0, t * FS) for t in atk], 2e-3)
    c1 = [round((1.0 - math.exp(-1.0 / (t * FS))) * 2 ** 31) for t in tau]
    c16 = [round((1.0 - math.exp(-CTL / (t * FS))) * 2 ** 31) for t in tau]
    emit("uint32_t", "VS_ENV_C1_Q31", c1, "decay / release: 1 - e^(-1 / (tau fs)), a frame, Q31")
    emit("uint32_t", "VS_ENV_C16_Q31", c16, "the same a control block of 16 frames: 1 - e^(-16 / (tau fs)), Q31 (16 frames of C1, exactly)")
    check("VS_ENV_C1_Q31", [v / 2 ** 31 for v in c1], [1.0 - math.exp(-1.0 / (t * FS)) for t in tau], 2e-4)
    check("VS_ENV_C16_Q31", [v / 2 ** 31 for v in c16], [1.0 - math.exp(-CTL / (t * FS)) for t in tau], 2e-5)
    sus = T("kAmpSustainLevel", 128)
    if any(abs(v * 2048 - round(v * 2048)) > 1e-3 for v in sus):
        fail("Synth2: the amp sustain table left its 1/2048 grid")
    emit("uint16_t", "VS_AMP_SUSTAIN_Q11", [round(v * 2048) for v in sus], "amp env sustain, Q11: the original's own 11-bit grid (2048 = 1.0); the filter env's is linear, S / 127", 16)

    # ---- levels
    gain = T("kAmpGain", 128)
    emit("uint16_t", "VS_AMP_GAIN_Q12", [round(v * 4096) for v in gain], "GAIN, linear, 1.0 at knob 64, Q12", 16)
    check("VS_AMP_GAIN_Q12", [round(v * 4096) / 4096 for v in gain], gain, 2e-4, relative=False)
    db = [round(10.0 ** (-(i / 8.0) / 20.0) * 32768) for i in range(241)]
    emit("uint16_t", "VS_DB_GAIN_Q15", db, "10^(-x / 20), x = 0..30 dB in steps of 1/8, Q15: the velocity law, dB = 15 (sens / 64) (127 - vel) / 126", 16)
    xs = [k / 64.0 for k in range(30 * 64 + 1)]
    check("VS_DB_GAIN_Q15", [lerp_table(db, x * 8, 32768) for x in xs], [10.0 ** (-x / 20.0) for x in xs], 2e-3)
    vel = T("kFilterVelScale", 128)
    emit("uint16_t", "VS_FLT_VEL_Q15", [round(v * 32768) for v in vel], "filter env amount x this, by velocity, when VEL SW is on, Q15", 16)

    # ---- FM (Voice.hpp: step = inc + beta x kFmRefInc x osc2; FM 0 is no FM at all)
    beta = T("kFmBeta", 128)
    dev = [0] + [round(b * fm_ref * 2 ** 32) for b in beta[1:]]
    emit("uint32_t", "VS_FM_DEV_Q32", dev, "FM: OSC1's phase-step deviation a frame at OSC2 = 1.0, cycles x 2^32 (0.5 cycle at 127); knob 0 = none")
    check("VS_FM_DEV_Q32", [v / 2 ** 32 for v in dev[1:]], [b * fm_ref for b in beta[1:]], 1e-4)

    # ---- filters (Filter.hpp FilterTables: per 1/32 knob there; per 1/4 knob here, linear between)
    lad_hz, lad_comp = T("kLadderCutoffHz", 128), T("kLadderFeedbackComp", 128)

    def svf_f(knob):
        hz = 16.7 * 2.0 ** (min(knob, 125.0) / 12.624)
        return 2.0 * math.sin(math.pi * min(hz, FS) / (2.0 * FS))

    def ladder(knob):
        i = min(int(knob), 126)
        t = knob - i
        lhz = math.exp(math.log(lad_hz[i]) * (1 - t) + math.log(lad_hz[i + 1]) * t)
        g = math.tan(math.pi * min(lhz, FS * 0.49) / FS)
        return g / (1 + g), lad_comp[i] * (1 - t) + lad_comp[i + 1] * t

    q = [k / 4.0 for k in range(127 * 4 + 1)]
    f_tab = [round(svf_f(k) * 2 ** 30) for k in q]
    a_tab = [round(ladder(k)[0] * 2 ** 31) for k in q]
    k_tab = [round(ladder(k)[1] * 32768) for k in q]
    emit("uint32_t", "VS_SVF_F_Q30", f_tab, "LP12 / HP12 / BP12: f = 2 sin(pi fc / (2 fs)), fc = 16.7 Hz x 2^(knob / 12.624) held at knob 125; per 1/4 knob, 0..127, Q30")
    emit("uint32_t", "VS_LAD_A_Q31", a_tab, "LP24: a stage's g / (1 + g), g = tan(pi fc / fs), fc from the measured table (log between knobs); per 1/4 knob, Q31")
    emit("uint16_t", "VS_LAD_COMP_Q15", k_tab, "LP24: the feedback's compensation, k = (0.0297 res - 0.076) x this; per 1/4 knob, Q15", 16)
    fine = [k / 32.0 for k in range(127 * 32 + 1)]
    check("VS_SVF_F_Q30", [lerp_table(f_tab, k * 4, 2 ** 30) for k in fine], [svf_f(k) for k in fine], 5e-5)
    check("VS_LAD_A_Q31", [lerp_table(a_tab, k * 4, 2 ** 31) for k in fine], [ladder(k)[0] for k in fine], 2e-4)
    check("VS_LAD_COMP_Q15", [lerp_table(k_tab, k * 4, 32768) for k in fine], [ladder(k)[1] for k in fine], 1e-4, relative=False)
    lim = [min(65535, round(65536 * (1.0 + (i / 32.0 / 1.038) ** 11.54) ** (-0.856 / 11.54))) for i in range(64 * 32 + 2)]
    if not re.search(r"kT = 1\.038, kP = 0\.856, kK = 11\.54", filt) or not re.search(r"kLimitMax = 64\.0, kLimitSteps = 32\.0", filt):
        fail("Synth2: the output limiter's constants moved")
    emit("uint16_t", "VS_LIMIT_Q16", lim, "the filters' output limiter: gain (1 + (e / 1.038)^11.54)^(-0.856 / 11.54) for its follower e = 0..64 in steps of 1/32 (Synth2's own grid), Q16 (65535: 1.0)", 16)
    xs = [k / 256.0 for k in range(64 * 256 + 1)]
    check("VS_LIMIT_Q16", [lerp_table(lim, x * 32, 65536) for x in xs], [(1.0 + (x / 1.038) ** 11.54) ** (-0.856 / 11.54) for x in xs], 1e-3)
    agc = [min(65535, round(65536 * (1.0 if i / 8.0 <= agc_t else (agc_t / (i / 8.0)) ** agc_k))) for i in range(64 * 8 + 1)]
    emit("uint16_t", "VS_AGC_Q16", agc, f"LP24's AGC on the feedback: (T / e)^{agc_k} above T = {agc_t}, 1 below, e = 0..64 in steps of 1/8, Q16 (65535: 1.0)", 16)
    xs = [agc_t + 0.125 + k / 64.0 for k in range(int((64 - agc_t - 0.125) * 64))]
    check("VS_AGC_Q16", [lerp_table(agc, x * 8, 65536) for x in xs], [(agc_t / x) ** agc_k for x in xs], 2e-3)
    # ---- LPDL (Filter.hpp SetDiodeCoefficients / Diode): w, k, g per res row (0 16 .. 112 127) x cutoff / 4 (32 points)
    lw, lk, lg = T("kLpdlW", 288), T("kLpdlK", 288), T("kLpdlG", 288)
    if not re.search(r"kRes\[9\] = \{0, 16, 32, 48, 64, 80, 96, 112, 127\}", filt) or \
            not re.search(r"kLpdlInputRef = 1\.3, kLpdlDrive = 1\.0, kLpdlFeedbackSat = 2\.0", filt) or \
            not re.search(r"h = 0\.25 / sampleRate_, wh = 2 \* M_PI \* 100\.0", filt):
        fail("Synth2: LPDL's grid or constants moved (Filter.hpp)")
    emit("int32_t", "VS_LPDL_LW_Q24", [round(math.log2(v) * 2 ** 24) for v in lw], "LPDL: log2 of the ladder's rate w (rad/s) [res row x 32 + cutoff / 4], Q24 (log between cutoffs, as Synth2)", 6)
    emit("int32_t", "VS_LPDL_K_Q16", [round(v * 65536) for v in lk], "LPDL: the feedback k, the same grid, Q16 (linear between)")
    emit("int32_t", "VS_LPDL_G_Q16", [round(v * 65536) for v in lg], "LPDL: the output gain g, the same grid, Q16 (linear between)")
    out.append(f"#define VS_LPDL_WH_Q30 {round(2 * math.pi * 100.0 * 0.25 / FS * 2 ** 30)}            /* LPDL: h x 2 pi 100 (the feedback's high-pass), h = 0.25 / fs, Q30 */")
    out.append(f"#define VS_LPDL_LOG2H_Q24 ({round(math.log2(0.25 / FS) * 2 ** 24)})       /* log2(h), h = 0.25 / fs (a 2 x oversampled step's trapezoid), Q24 */")
    out.append(f"#define VS_LPDL_MAXLW_Q24 {round(max(math.log2(v) for v in lw) * 2 ** 24)}        /* the largest log2 w (checks h w stays under 2) */")

    def tox(x2):
        return 1.0 / math.sqrt(x2) if x2 > 24.7 else (135135 + x2 * (17325 + x2 * (378 + x2))) / (135135 + x2 * (62370 + x2 * (3150 + 28 * x2)))
    tx = [round(tox(i / 32.0) * 2 ** 30) for i in range(1025)]
    emit("int32_t", "VS_TANHX_Q30", tx, "tanh(x) / x by x^2 = 0..32 in steps of 1/32 (Synth2's TanhOverX: Lambert's fraction, 1 / |x| above x^2 = 24.7), Q30", 6)
    xs = [k / 512.0 for k in range(32 * 512)]
    check("VS_TANHX_Q30", [lerp_table(tx, x * 32, 2 ** 30) for x in xs], [tox(x) for x in xs], 2e-4, relative=False)

    sat = T("kSaturationA", 128)
    emit("uint32_t", "VS_SAT_A_Q16", [round(v * 65536) for v in sat], "SATURATION: y = (1 + a) x / (1 + a |x|), a by knob, Q16")
    check("VS_SAT_A_Q16", [round(v * 65536) / 65536 for v in sat], sat, 1e-5, relative=False)
    kbd = T("kKbdTrack", 128)
    emit("uint32_t", "VS_KBD_TRACK_Q16", [round(v * 12.624 / 12.0 * 65536) for v in kbd], "KBD TRACK: cutoff knob units a semitone from key 48 (the table's octaves an octave x 12.624 / 12), Q16")

    # ---- LFOs (Lfo.hpp)
    hz = [2.0 ** (s / 12.0367) / 12.0 for s in range(128)]
    lfo = [round(h / FS * 2 ** 32) for h in hz]
    emit("uint32_t", "VS_LFO_INC_Q32", lfo, "LFO SPEED: the phase step a frame, Hz = 2^(s / 12.0367) / 12, Q32 (a control block: x 16)")
    check("VS_LFO_INC_Q32", [v / 2 ** 32 * FS for v in lfo], hz, 1e-4)
    cents = T("kLfoPitchCents", 128)
    emit("uint16_t", "VS_LFO_STEPS", [int(c / 9.375 + 0.5) for c in cents], "an LFO on pitch: its 1/128-octave steps at full swing, by DEPTH (Lfo::PitchSteps; DEPTH 0 is no route)", 16)
    lsrc = (s2 / "EngineCore/Lfo.hpp").read_text()
    if not re.search(r"std::exp2\(speed / 12\.0367\) / 12\.0", lsrc):
        fail("Synth2: the LFO speed law moved (Lfo.hpp SpeedHz)")
    m = re.search(r"kSyncBeats\[kSyncSteps\] = \{([^}]*)\}", lsrc)
    items = [x.strip() for x in m.group(1).split(",")] if m else []
    if len(items) != 30 or not all(re.fullmatch(r"[\d.]+( / [\d.]+)?", x) for x in items):
        fail("Synth2: the LFO sync table moved (Lfo.hpp kSyncBeats)")
    beats = [float(x.split("/")[0]) / (float(x.split("/")[1]) if "/" in x else 1.0) for x in items]
    bk = [round(2 ** 48 / (60.0 * b_ * FS)) for b_ in beats]
    emit("uint32_t", "VS_LFO_BEAT_Q48", bk, "TEMPO on: the phase step a frame at 1 bpm, 2^32 / (60 x beats x fs), Q16 more (x bpm Q8 >> 24); step = SPEED x 30 / 128 (Lfo::kSyncBeats, 16 bars .. 1/64T)", 4)
    check("VS_LFO_BEAT_Q48", [v * 120 / 2 ** 16 for v in bk], [2 ** 32 * 2.0 / b_ / FS for b_ in beats], 1e-6)
    sn = [round(math.sin(2 * math.pi * i / 1024) * 2 ** 30) for i in range(1025)]
    emit("int32_t", "VS_SIN_Q30", sn, "the sine LFO: sin(2 pi i / 1024), i = 0..1024, Q30, linear between entries", 6)

    # ---- the bus's tone stage (Effects.hpp BilinearOnePole, Eq::Process): always on; at 64 it is the original's
    # 22 kHz output low-pass. Its peak filter, and the delay's tone, come with Stage 4d
    tone = T("kEqToneHz", 128)
    kk = [math.pi * hz / FS for hz in tone]
    tg = [round((1.0 if t > 64 else k) / (1.0 + k) * 2 ** 30) for t, k in enumerate(kk)]
    tb = [round((1.0 - k) / (1.0 + k) * 2 ** 30) for k in kk]
    emit("uint32_t", "VS_TONE_G_Q30", tg, "EQ TONE, a bilinear one-pole with no prewarp, k = pi fc / fs: y = g (x + x1) + b y1 up to 64 (a low-pass), y = g (x - x1) + b y1 above (a high-pass); g, Q30")
    emit("int32_t", "VS_TONE_B_Q30", tb, "its b = (1 - k) / (1 + k), Q30")
    check("VS_TONE_G_Q30", [v / 2 ** 30 for v in tg], [(1.0 if t > 64 else k) / (1.0 + k) for t, k in enumerate(kk)], 1e-6)

    # ---- DETUNE (Voice.hpp): 8 copies at kDetuneOffsets x d cents, d = 20 DETUNE / 127
    offs = synth2.c_array(voice, "kDetuneOffsets")
    if len(offs) != 8:
        fail("Synth2: kDetuneOffsets is not 8 copies")
    det = [round(2.0 ** (o * (20.0 * d / 127.0) / 1200.0) * 2 ** 30) for d in range(128) for o in offs]
    emit("uint32_t", "VS_DETUNE_Q30", det, f"DETUNE: copy k's step over OSC1's, 2^(o_k x 20 d / 127 / 1200), o = {[int(o) for o in offs]}; [knob x 8 + k], Q30")
    check("VS_DETUNE_Q30", [v / 2 ** 30 for v in det], [2.0 ** (o * (20.0 * d / 127.0) / 1200.0) for d in range(128) for o in offs], 1e-9)
    deg = synth2.c_array(voice, "kCopyPhaseDeg")
    if len(deg) != 8:
        fail("Synth2: kCopyPhaseDeg is not 8 copies")
    emit("uint16_t", "VS_COPY_PHASE_DEG", [int(d) for d in deg], "OSC PHASE above 0: copy k starts this many degrees x (v - 1) / 126 after OSC1's start")
    out.append(f"#define VS_COPY_GAIN_Q15 {round(0.297 * 32768)}                  /* a detuned stack's gain (OSC1, its copies; the SUB, its copies): 0.297 .. */")
    out.append(f"#define VS_COPY_GAIN_SINE_Q15 {round(0.288 * 32768)}             /* .. 0.288 with OSC1 a sine */")
    if not re.search(r"detuneGain = shape1 == 0 \? 0\.288 : 0\.297", voice):
        fail("Synth2: the detune gain moved (Voice.hpp detuneGain)")
    out.append("")

    # ---- the mod env on FM: its decay reaches the FM knob in dB (Voice.hpp: g = 1 + ln(e) / ln(1e4)): log2 of a
    # level's mantissa, from which g = 1 + log2(e) / log2(1e4)
    lg = [round(math.log2(1.0 + i / 256.0) * 65536) for i in range(257)]
    emit("uint32_t", "VS_LOG2_Q16", lg, "log2(1 + i / 256), i = 0..256, Q16: a level's log2 from its top bit and this, linear between entries")
    xs = [1.0 + k / 4096.0 for k in range(4096)]
    check("VS_LOG2_Q16", [lerp_table(lg, (x - 1) * 256, 65536) for x in xs], [math.log2(x) for x in xs], 2e-5, relative=False)
    if not re.search(r"1\.0 \+ std::log\(e\) / std::log\(1e4\)", voice):
        fail("Synth2: the mod env's FM law moved (Voice.hpp: 1 + log(e) / log(1e4))")
    out.append(f"#define VS_MENV_FM_K_Q16 {round(65536 / math.log2(1e4))}                 /* 1 / log2(1e4), Q16: g = 1 + log2(e) x this */")
    out.append("")

    # ---- unison, portamento, the slots' start phases
    uni = T("kUnisonDetuneCents", 128)
    emit("uint16_t", "VS_UNI_DETUNE_Q8", [round(c * 256) for c in uni], "UNISON DETUNE: the stack spreads over +- this many cents, Q8", 16)
    porta = T("kPortaTau", 128)
    pa = [0 if t <= 0 else round(math.exp(-16.0 / (t * FS)) * 2 ** 31) for t in porta]
    emit("uint32_t", "VS_PORTA_A_Q31", pa, "PORTAMENTO: a = e^(-16 / (tau fs)) for its 16-frame step r <- max(r a - E (1 - a), 0), Q31; knob 0 (0 here): off")
    check("VS_PORTA_A_Q31", [v / 2 ** 31 for v in pa[1:]], [math.exp(-16.0 / (t * FS)) for t in porta[1:]], 1e-6, relative=False)
    NSLOT = 16                                           # vs_build.h allows VS_NV up to 16; Synth2 has 32 slots
    p1, p2, pc = T("kSlotOsc1Phase", 32), T("kSlotOsc2Phase", 32), T("kSlotCopyPhase", 256)
    wrap = lambda v: round(v * 2 ** 32) % 2 ** 32
    out.append(f"#define VS_NSLOT {NSLOT}u                            /* voice slots these start phases cover */")
    emit("uint32_t", "VS_SLOT_OSC1_Q32", [wrap(v) for v in p1[:NSLOT]], "OSC PHASE 0: a voice slot's OSC1 phase at power-on, cycles x 2^32 (and UNISON PHASE's shift of stack voice k)", 4)
    emit("uint32_t", "VS_SLOT_OSC2_Q32", [wrap(v) for v in p2[:NSLOT]], "the same for OSC2", 4)
    emit("uint32_t", "VS_SLOT_COPY_Q32", [wrap(v) for v in pc[:NSLOT * 8]], "the same for the 8 DETUNE copies: [slot x 8 + copy], the copies at -7, -5, -3, -1, 1, 3, 5, 7 x d", 4)

    OUT.write_text("\n".join(out))
    n = sum(1 for l in out if l.startswith("static const"))
    print(f"gen_tables: {OUT.relative_to(ROOT)}: {n} tables")
    print("\n".join(report))


