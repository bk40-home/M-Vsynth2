"""Generate docs/cheatsheet.html from firmware/gen/vs_params.h: the panel's pages, the buttons, the CC map.

  python3 tools/gen_cheatsheet.py          (fails if a parameter is on no page, or on two: proposal 7.2)

One sheet, printable. Its contents are the firmware's own tables, so it can not drift from what the FM-1 does."""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
H = (ROOT / "firmware/gen/vs_params.h").read_text()
OUT = ROOT / "docs/cheatsheet.html"


def fail(m):
    sys.exit(f"gen_cheatsheet: {m}")


params = re.findall(r'\{(-?\d+), (-?\d+), (-?\d+), (-?\d+), VS_SEC_(\w+), VS_K_(\w+), (\d+), (\d+), "([^"]*)"\},\s*/\* (\d+) ([^*]*)\*/', H)
NALL = 99 + int(re.search(r"#define VS_NOWN (\d+)u", H).group(1))   # Synth1's 99, then M-Vsynth2's own (LFO FADE)
if len(params) != NALL:
    fail(f"{len(params)} parameters read from vs_params.h, not {NALL}")
P = {int(p[9]): {"label": p[8], "sec": p[4], "lo": int(p[0]), "hi": int(p[1]), "what": p[10].strip()} for p in params}
pages = [(b, int(n), int(of), [int(x) for x in ids.split(",")], t) for b, n, of, ids, t in
         re.findall(r'\{VS_BTN_(\w+), (\d+), (\d+), \{([\d, ]+)\}, "([^"]*)"\}', H)]
seen = {}
for b, n, of, ids, t in pages:
    for i in ids:
        if i != 255:
            seen[i] = seen.get(i, 0) + 1
missing = [i for i in range(NALL) if seen.get(i, 0) == 0 and i != 59]
twice = [i for i, c in seen.items() if c > 1]
if missing or twice:
    fail(f"on no page: {missing}; on two: {twice}")
ccm = re.search(r"VS_CC_PARAM\[128\] = \{([^}]*)\}", H)
cc = [int(x) for x in re.findall(r"\d+", ccm.group(1))] if ccm else []

rows = []
for b, n, of, ids, t in pages:
    title = t + (f" {n}/{of}" if of > 1 else "")
    cells = "".join(f"<td>{P[i]['label']}<small> {i}</small></td>" if i != 255 else "<td></td>" for i in ids)
    rows.append(f"<tr><th>{b}</th><td class=t>{title}</td>{cells}</tr>")
ccrows = [f"<tr><td>{c}</td><td>{P[p]['sec']}</td><td>{P[p]['label']}</td><td><small>{P[p]['what']}</small></td></tr>"
          for c, p in enumerate(cc) if p < 99]
html = f"""<!DOCTYPE html>
<!-- SPDX-License-Identifier: GPL-3.0-only. GENERATED by tools/gen_cheatsheet.py from firmware/gen/vs_params.h -->
<html lang="en"><head><meta charset="utf-8"><title>M-Vsynth2 cheat sheet</title><style>
body{{font:13px system-ui,sans-serif;margin:24px;max-width:1000px;color:#111}}h1{{color:#00a080;margin:0}}h2{{margin-top:24px}}
table{{border-collapse:collapse;width:100%}}td,th{{border-bottom:1px solid #ddd;padding:3px 6px;text-align:left}}th{{color:#00a080}}
small{{color:#888}}.t{{font-weight:600}}.cols{{columns:2}}@media print{{body{{margin:8mm}}}}
</style></head><body>
<h1>M-Vsynth2</h1><p>Synth2 (the open-source Synth1) on the M-VAVE FM-1. Every patch parameter is on a page; the number is its <code>.sy1</code> index.</p>
<h2>Buttons</h2><table>
<tr><th>LFO EDIT ENV SEL FX GLO</th><td>a section: the first press opens its page, the next steps through them (GLO ends on HOME KNOBS, the patch's choice of HOME's four knobs; then GLOBAL 1/4: MIDI CH, VOICES, TEMPO; 2/4: THEME, COLOUR, BT MIDI; 3/4 KEYS: TOUCH (velocity and pressure from the keys), CURVE, SENS; 4/4: DIAG)</td></tr>
<tr><th>ARP</th><td>tap: the arp on / off; hold: the ARP page</td></tr>
<tr><th>KNOB 1..4</th><td>the page's four columns (HOME: the patch's HOME KNOBS; FREQ, RES, AMOUNT, GAIN unless set)</td></tr>
<tr><th>SELECT</th><td>the column last turned, one step at a time</td></tr><tr><th>ALGORITHM</th><td>every page in turn</td></tr>
<tr><th>PRESETS</th><td>the program (slots that hold a patch)</td></tr><tr><th>HOME</th><td>the home screen</td></tr>
<tr><th>SEQ</th><td>the bank browser (K1 the bank, past U8 FAVOURITES; turning plays the slot; K2 stars it)</td></tr>
<tr><th>SAVE</th><td>the save screen (K1 bank U1..U8, K2 slot: it shows what it replaces, K3 the cursor in the name, K4 or SELECT its character); SAVE again writes, any other button leaves</td></tr>
<tr><th>OCT- OCT+</th><td>the octave</td></tr></table>
<h2>Pages</h2><table><tr><th>Button</th><th>Page</th><th>KNOB 1</th><th>KNOB 2</th><th>KNOB 3</th><th>KNOB 4</th></tr>
{''.join(rows)}</table>
<h2>MIDI CC map</h2><p>Ours, not Synth1's (Synth1 has none of its own): every knob sends and receives on these. CC 0 bank select (0 FACTORY, 1..8 U1..U8),
CC 1 the INIT patch's mod-wheel route, 64 sustain, 120 / 123 all off. A patch's two CTRL routes act as well.</p>
<div class=cols><table><tr><th>CC</th><th>Section</th><th>Knob</th><th></th></tr>{''.join(ccrows)}</table></div>
</body></html>
"""
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(html)
print(f"gen_cheatsheet: {OUT.relative_to(ROOT)}: {len(pages)} pages, {len(ccrows)} CCs")
