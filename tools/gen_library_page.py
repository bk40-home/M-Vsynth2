"""Generate docs/library.html: M-Vsynth2's patch library page (fm1-kit's library, M-Vsynth2's adapter).

  python3 tools/gen_library_page.py                  (needs Synth2: tools/synth2.py; the output is committed)
  python3 tools/gen_library_page.py --data OUT.json  the page's data plus tools/sy1.py's own results, for
                                                     tests/library_test.js (no page written)

In the page: the .sy1 rules of tools/sy1.py as data (Synth2's ranges, defaults and legacy conversion), the Synth2
Factory bank (tools/bank/factory/), library/adapter-mvsynth2.js (files and the vs_xfer.h SysEx) and
library/mock-mvsynth2.js (the Sandbox). docs/bank.html, the page this replaces, now points here."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "third_party/fm1-kit/tools"))
import sy1                      # noqa: E402
from build_library import build  # noqa: E402

OUT = ROOT / "docs/library.html"
OLD = ROOT / "docs/bank.html"
REDIRECT = """<!DOCTYPE html>
<!-- SPDX-License-Identifier: GPL-3.0-only. GENERATED by tools/gen_library_page.py: the bank page became library.html -->
<html lang="en"><head><meta charset="utf-8"><title>M-Vsynth2 library</title>
<meta http-equiv="refresh" content="0; url=library.html"></head>
<body style="font:14px system-ui,sans-serif;background:#0B0F10;color:#E8F0F0;margin:24px">
<p>The bank page is now the <a href="library.html" style="color:#00C8A0">patch library</a>.</p></body></html>
"""


def version():
    for line in (ROOT / "tools/build.py").read_text().splitlines():
        if line.startswith("VERSION") and "=" in line:
            v = line.split("=", 1)[1].split("#")[0].strip().strip("\"'")
            if v and v != "None":
                return v
    return "dev"


def check_data(data):
    """tools/sy1.py's answers for the same files: the test holds the page to them byte for byte"""
    import synth2
    chk = {"pack": {}, "write": {}, "legacy": [], "legacyPack": {}}
    for name, text in data["factory"]:
        p = sy1.parse(text.encode("latin-1"))
        chk["pack"][name] = sy1.pack(p).hex()
        chk["write"][name] = sy1.write(p).decode("ascii")
    r = synth2.root(False)
    if r:
        for f in sorted((Path(r) / "Shared/Resources").rglob("*.sy1")):
            raw = f.read_bytes()
            key = str(f.relative_to(r))
            chk["legacy"].append([key, raw.decode("latin-1")])
            chk["legacyPack"][key] = sy1.pack(sy1.parse(raw)).hex()
    data["check"] = chk
    return data


def main():
    t = sy1.tables()
    data = {"sy1": {k: t[k] for k in ("lo", "hi", "de", "tab", "poly", "mono")}}
    data["sy1"]["rules"] = [list(r) for r in t["rules"]]
    fac = sorted((ROOT / "tools/bank/factory").glob("*.sy1"))
    data["factory"] = [[f.name, f.read_bytes().decode("latin-1")] for f in fac]
    if "--data" in sys.argv:
        import json
        out = Path(sys.argv[sys.argv.index("--data") + 1])
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(check_data(data)))
        print(f"gen_library_page: {out} (the test's data)")
        return
    n = build(OUT, data, [ROOT / "library/adapter-mvsynth2.js", ROOT / "library/mock-mvsynth2.js"],
              stamp="M-Vsynth2 " + version())
    OLD.write_text(REDIRECT)
    print(f"gen_library_page: {OUT.relative_to(ROOT)} ({n} bytes, {len(fac)} factory patches); {OLD.relative_to(ROOT)} points to it")


if __name__ == "__main__":
    main()
